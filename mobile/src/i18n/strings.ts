export const strings: Record<Lang, Record<StringKey, string>> = { en, hi };

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  const template = strings[lang][key] ?? strings.en[key];
  return params ? template.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`)) : template;
}
